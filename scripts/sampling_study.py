"""Evaluation-only sampling study for a trained text NCM and its matched AR baseline (experiment E27).

Draws samples under different sampling policies (global and per-level temperature, top-k, top-p, a
sharpened level-0 unigram for the NCM; temperature, top-k and top-p for the AR baseline), scores them with
the pinned GPT-2-large scorer and writes one JSON result and one sample file per run. Nothing is trained.

    python scripts/sampling_study.py scripts/sampling_study_runs.json \\
        --checkpoint e21=artifacts/tinystories-e21/export --checkpoint e24-seed1=artifacts/tinystories-e24-seed1/export \\
        --data artifacts/tinystories/v2-bpe8192-L128 --out artifacts/sampling-study

Each checkpoint directory is a converted text export holding ``spec.json``, the NCM weights and
``ar.safetensors``. A run list is a JSON array of objects with ``id``, ``model`` (``ncm``, ``ar`` or
``data`` for held-out real text), ``ckpt`` (a name given to ``--checkpoint``), ``seeds``, ``n`` (samples
per seed, default 256) and ``params``:

* ``T``: temperature for every level (NCM) or position (AR), default 1.
* ``band_T``, ``band_k``, ``band_p``: lists of ``[first_level, last_level, value]`` that override the
  temperature, top-k or top-p of the generated levels in that range. Level index 0 is the one drawn from
  the stored unigram; indices 1 to 11 are generated by the model.
* ``top_k``, ``top_p``: for every level (NCM) or position (AR).
* ``uT``: temperature of the stored level-0 unigram (NCM only).

Finished runs are skipped, so an interrupted study resumes. A run with ``gate: [low, high]`` stops the study
when its mean perplexity falls outside the range; use it on the first run to confirm that the setup
reproduces a known value. ``--selftest`` first checks that the per-level sampler equals the library sampler
at its default settings. Memory is capped by NCM_MLX_MEMORY_LIMIT_GB (default 10 GB on macOS, otherwise 90%
of the device). The scripts/sampling_study_runs.json list holds the 98 runs of E27.
"""

import argparse
import json
import math
import os
import statistics
import sys
import time
from pathlib import Path

import mlx.core as mx
import numpy as np

from ncm_mlx.official import sample
from ncm_mlx.official import text_eval as te
from ncm_mlx.official import tinystories as ts
from ncm_mlx.official.ar import TextAR
from ncm_mlx.official.bpe import BPETokenizer


def log(*a) -> None:
    print(time.strftime("%H:%M:%S"), *a, flush=True)


class Study:
    def __init__(self, checkpoints: dict[str, Path], data: Path, scorer_dir: Path, out: Path):
        self.checkpoints = checkpoints
        self.data = data
        self.scorer_dir = scorer_dir
        self.out = out
        self._models: dict = {}
        self._scorer = None
        self._openings = None
        self._bpe = None

    @property
    def bpe(self) -> BPETokenizer:
        if self._bpe is None:
            first = next(iter(self.checkpoints.values()))
            self._bpe = BPETokenizer.load(first / "bpe.json")
        return self._bpe

    def ncm(self, name: str):
        if ("ncm", name) not in self._models:
            m = sample.load(self.checkpoints[name])
            mx.eval(m.codec.parameters(), m.gen.parameters())
            self._models[("ncm", name)] = m
        return self._models[("ncm", name)]

    def ar(self, name: str) -> TextAR:
        if ("ar", name) not in self._models:
            d = self.checkpoints[name]
            g = json.loads((d / "spec.json").read_text())["task"]["generator"]
            m = TextAR(8192, 128, g["dim"], g["n_layer"], g["n_head"], g["rope_base"])
            m.load_weights(str(d / "ar.safetensors"), strict=True)
            m.eval()
            mx.eval(m.parameters())
            self._models[("ar", name)] = m
        return self._models[("ar", name)]

    def scorer(self) -> te.Scorer:
        if self._scorer is None:
            self._scorer = te.Scorer(self.scorer_dir)
        return self._scorer

    def openings(self) -> set:
        if self._openings is None:
            self._openings = te.train_opening_index(np.asarray(ts.load_split(self.data, "train")))
        return self._openings

    def sampler(self, kind: str, ckpt: str, params: dict):
        if kind == "ncm":
            m = self.ncm(ckpt)
            return lambda batch, seed: generate_ncm(m, batch, seed, **params)
        m = self.ar(ckpt)
        return lambda batch, seed: m.generate(batch, params.get("T", 1.0), params.get("top_k", 0),
                                              params.get("top_p", 1.0), seed)

    def perplexity(self, texts_by_seed: dict[int, list[str]]) -> dict:
        per, unscorable = {}, 0
        for seed, texts in texts_by_seed.items():
            res = self.scorer().token_nll(texts)
            total = sum(a for a, _ in res)
            count = sum(c for _, c in res)
            unscorable += sum(c == 0 for _, c in res)
            per[seed] = math.exp(total / count)
        values = list(per.values())
        return {"per_seed": {str(k): round(v, 3) for k, v in per.items()},
                "mean": round(statistics.mean(values), 3),
                "sd": round(statistics.stdev(values), 3) if len(values) > 1 else 0.0,
                "unscorable": unscorable}

    def run(self, spec: dict) -> dict:
        path = self.out / "results" / f"{spec['id']}.json"
        if path.exists():
            log("skip", spec["id"])
            return json.loads(path.read_text())
        t0 = time.time()
        seeds, n = spec["seeds"], spec.get("n", 256)
        if spec["model"] == "data":
            test = np.asarray(ts.load_split(self.data, "test"))
            rows_by_seed = {s: test[i * n:(i + 1) * n].tolist() for i, s in enumerate(seeds)}
        else:
            run = self.sampler(spec["model"], spec["ckpt"], spec.get("params", {}))
            rows_by_seed = te.draw(run, n, seeds, 128)
        texts_by_seed = {s: [self.bpe.decode(te.cut(x), skip_special=True) for x in rows]
                         for s, rows in rows_by_seed.items()}
        rows = [x for v in rows_by_seed.values() for x in v]
        texts = [t for v in texts_by_seed.values() for t in v]
        result = dict(spec)
        result["diagnostics"] = te.diagnostics(rows, texts, self.bpe, self.openings())
        result["gen_ppl"] = self.perplexity(texts_by_seed)
        result["wall_seconds"] = round(time.time() - t0, 1)
        te.write_samples(self.out / "samples" / f"{spec['id']}.jsonl", spec["id"], rows_by_seed, texts_by_seed)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(result, indent=1) + "\n")
        d = result["diagnostics"]
        log(f"{spec['id']}: ppl {result['gen_ppl']['mean']} distinct-2 {d['distinct_2']} "
            f"distinct-3 {d['distinct_3']} repeated-4gram {d['repeated_4gram_pct']} ({result['wall_seconds']}s)")
        return result


def generate_ncm(m, batch: int, seed: int, T: float = 1.0, band_T=(), uT: float = 1.0, top_k: int = 0,
                 top_p: float = 1.0, band_k=(), band_p=()) -> mx.array:
    """``sample.generate`` with per-level temperature, top-k and top-p and a sharpened level-0 unigram.

    Level index 0 is the stored-unigram level; the others are generated by the model, one forward each,
    with the reference (uncached) prefix path.
    """
    codec, gen = m.codec, m.gen
    n = len(codec.levels)
    temps, ks, ps = [T] * n, [top_k] * n, [top_p] * n
    for table, bands in ((temps, band_T), (ks, band_k), (ps, band_p)):
        for lo, hi, value in bands:
            for i in range(int(lo), int(hi) + 1):
                table[i] = value
    prefix = sample.unconditional_prefix(m, batch)
    keys = mx.random.split(mx.random.key(seed), n + 1)
    prefix_emb = gen.prefix_embedding(prefix)
    log_p0 = mx.log(m.level0_unigram) / uT
    c0 = mx.random.categorical(log_p0, shape=(batch, codec.levels[0]), key=keys[0])
    z = codec.level_contribution(c0, 0)
    for k in range(1, n):
        logits = gen.level_logits(k - gen.first, codec.pool(z, k), prefix_emb, prefix)
        c = sample.sample_codes(logits, temps[k], int(ks[k]), ps[k], keys[k])
        z = z + codec.level_contribution(c, k)
    return mx.argmax(codec.decode_logits(z), axis=-1)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("runs", help="JSON run list")
    ap.add_argument("--checkpoint", action="append", default=[], metavar="NAME=DIR",
                    help="converted text export (spec.json, NCM weights, ar.safetensors, bpe.json); repeatable")
    ap.add_argument("--data", type=Path, default=Path("artifacts/tinystories/v2-bpe8192-L128"),
                    help="tokenised TinyStories split directory")
    ap.add_argument("--scorer", type=Path, default=te.SCORER_DIR, help="GPT-2-large snapshot directory")
    ap.add_argument("--out", type=Path, default=Path("artifacts/sampling-study"))
    ap.add_argument("--selftest", action="store_true", help="check the per-level sampler against sample.generate")
    args = ap.parse_args()

    default_gb = 10.0 if sys.platform == "darwin" else 0.9 * mx.device_info().get("memory_size", 0) / 2**30
    limit = float(os.environ.get("NCM_MLX_MEMORY_LIMIT_GB", default_gb))
    if limit > 0:
        mx.set_memory_limit(int(limit * 2**30))
        mx.set_cache_limit(256 * 2**20)

    checkpoints = {}
    for item in args.checkpoint:
        name, _, directory = item.partition("=")
        if not directory:
            ap.error(f"--checkpoint needs NAME=DIR, got {item!r}")
        checkpoints[name] = Path(directory)
    runs = json.loads(Path(args.runs).read_text())
    missing = {r["ckpt"] for r in runs if r["model"] != "data"} - set(checkpoints)
    if missing:
        ap.error(f"run list needs checkpoints {sorted(missing)}; pass them with --checkpoint")

    study = Study(checkpoints, args.data, args.scorer, args.out)
    if args.selftest:
        m = study.ncm(next(iter(checkpoints)))
        a = np.array(generate_ncm(m, 16, 5))
        b = np.array(sample.generate(m, sample.unconditional_prefix(m, 16), temperature=1.0, seed=5).tokens)
        same = bool((a == b).all())
        log("selftest, per-level sampler equals sample.generate:", same)
        if not same:
            return 3
    for spec in runs:
        result = study.run(spec)
        if "gate" in spec:
            low, high = spec["gate"]
            if not low <= result["gen_ppl"]["mean"] <= high:
                log(f"gate failed for {spec['id']}: {result['gen_ppl']['mean']} is outside [{low}, {high}]")
                return 4
    return 0


if __name__ == "__main__":
    sys.exit(main())
